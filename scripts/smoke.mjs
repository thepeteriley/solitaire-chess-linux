import {_electron as electron} from 'playwright';
import {strict as assert} from 'node:assert';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE;
const profile='/tmp/solitaire-chess-ui-test-'+Date.now();
const packaged=process.env.SOLITAIRE_PACKAGED_APP;
const app=await electron.launch({...(packaged?{executablePath:packaged}:{}),args:[...(packaged?[]:[root]),`--user-data-dir=${profile}`],env});
const page=await app.firstWindow();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const cell=s=>page.locator(`[data-square="${s}"]`);
const boardState=()=>page.locator('.square').evaluateAll(es=>Object.fromEntries(es.map(e=>[e.dataset.square,e.getAttribute('aria-label')])));
const ready=async()=>{await page.waitForFunction(()=>document.querySelector('.engine-status')?.textContent.includes('Ready'),{timeout:15000});};
const load=async fen=>{await page.getByRole('button',{name:'Load position',exact:true}).first().click();await page.getByRole('textbox',{name:'FEN position'}).fill(fen);await page.locator('.modal').getByRole('button',{name:'Load position',exact:true}).click();};
try{
 await page.waitForSelector('.candidate-primary');await ready();
 assert.equal(await page.locator('.candidate-primary').count(),5);
 assert.equal(await page.locator('.square').count(),64);
 const controls=await page.locator('.game-controls').boundingBox();
 assert(controls.y+controls.height<=await page.evaluate(()=>innerHeight), 'game controls must fit the launch window');
 assert.match(await page.locator('footer').textContent(), /Private, on your device/);
 assert.equal(await page.locator('.nav-buttons svg').count(),2);
 const start=await boardState();
 fs.mkdirSync(path.join(root,'qa'),{recursive:true});
 await page.screenshot({path:path.join(root,'qa','opening.png')});
 await page.getByRole('button',{name:'Flip board',exact:true}).click();
 assert.equal(await page.locator('.square').first().getAttribute('data-square'),'h1');
 await page.getByRole('button',{name:'Flip board',exact:true}).click();
 await page.locator('.candidate-primary').first().click();
 assert(await page.locator('.nav-caption').textContent()==='Exploring a variation');
 const pv1=await boardState();assert.notDeepEqual(pv1,start);
 await page.keyboard.press('ArrowRight');const pv2=await boardState();assert.notDeepEqual(pv2,pv1);
 await page.keyboard.press('ArrowLeft');assert.deepEqual(await boardState(),pv1);
 await page.getByRole('button',{name:'Return to game'}).click();assert.deepEqual(await boardState(),start);
 await cell('e2').click();await cell('e4').click();await ready();
 assert.match(await cell('e4').getAttribute('aria-label'),/White pawn/);assert.equal(await cell('e2').getAttribute('aria-label'),'e2');
 await page.getByRole('button',{name:'Undo',exact:true}).click();await ready();assert.deepEqual(await boardState(),start);
 await page.getByRole('combobox',{name:'Play mode'}).selectOption('computer');
 await cell('e2').click();await cell('e4').click();
 await page.waitForFunction(()=>document.querySelector('[data-square="e4"]')?.getAttribute('aria-label')==='e4 White pawn'&&document.querySelector('.board-state')?.textContent==='White to move',{timeout:12000});
 assert(!/Computer is thinking/.test(await page.locator('.board-state').textContent()));
 await page.getByRole('button',{name:'Undo',exact:true}).click();await ready();assert.deepEqual(await boardState(),start);
 await page.getByRole('combobox',{name:'Your pieces'}).selectOption('b');
 await page.waitForFunction(()=>document.querySelector('.board-state')?.textContent==='Black to move',{timeout:12000});
 assert.equal(await page.locator('.square').first().getAttribute('data-square'),'h1');
 await page.getByRole('combobox',{name:'Play mode'}).selectOption('local');
 await load('7k/8/6K1/8/8/8/7R/8 b - - 0 1');await ready();
 assert.equal(await page.locator('.candidate-primary').count(),1);
 await load('7k/6Q1/5K2/8/8/8/8/8 b - - 0 1');
 await page.waitForSelector('.terminal');assert.match(await page.locator('.terminal').textContent(),/checkmate/);
 await load('7k/P7/8/8/8/8/8/7K w - - 0 1');await ready();
 await cell('a7').click();await cell('a8').click();await page.getByRole('button',{name:'Promote to knight',exact:true}).click();
 assert.match(await cell('a8').getAttribute('aria-label'),/White knight/);
 // Castling moves both pieces.
 await load('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1');await ready();
 await cell('e1').click();await cell('g1').click();
 assert.match(await cell('g1').getAttribute('aria-label'),/White king/);assert.match(await cell('f1').getAttribute('aria-label'),/White rook/);
 // En passant is legal and removes the passed pawn.
 await load('7k/8/8/3pP3/8/8/8/7K w - d6 0 1');await ready();await cell('e5').click();await cell('d6').click();
 assert.match(await cell('d6').getAttribute('aria-label'),/White pawn/);assert.equal(await cell('d5').getAttribute('aria-label'),'d5');
 await load('r1bq1rk1/ppp2ppp/2np1n2/2b1p3/2B1P3/2NP1N2/PPP2PPP/R1BQ1RK1 w - - 0 6');await ready();
 await page.screenshot({path:path.join(root,'qa','middlegame.png')});
 await page.locator('.candidate-primary').first().click();await page.keyboard.press('ArrowRight');
 await page.screenshot({path:path.join(root,'qa','variation.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS: real Electron UI, five legal candidates, flip, PV preview and keyboard navigation, return, legal move, undo, both computer sides, one legal move, checkmate, underpromotion, castling, en passant; no renderer errors.');
}finally{await app.close();fs.rmSync(profile,{recursive:true,force:true});}
