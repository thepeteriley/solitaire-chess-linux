import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const out=path.join(root,'release/linux/source');await fs.mkdir(out,{recursive:true});
for(const name of ['src','electron','index.html','vite.config.js','package-lock.json','tests'])await fs.cp(path.join(root,name),path.join(out,name),{recursive:true});
await fs.cp(path.join(root,'linux'),path.join(out,'linux'),{recursive:true,filter:p=>!p.includes('__pycache__')});
await fs.mkdir(path.join(out,'scripts'),{recursive:true});
for(const name of ['package-linux.mjs','prepare-linux-source.mjs','smoke.mjs'])await fs.copyFile(path.join(root,'scripts',name),path.join(out,'scripts',name));
await fs.mkdir(path.join(out,'resources'),{recursive:true});
for(const name of ['icon.png','privacy-policy.txt'])await fs.copyFile(path.join(root,'resources',name),path.join(out,'resources',name));
const pkg=JSON.parse(await fs.readFile(path.join(root,'package.json'),'utf8'));
pkg.license='MIT';pkg.repository='https://github.com/thepeteriley/solitaire-chess-linux';pkg.scripts={build:'vite build',start:'electron .',test:'node --test tests/*.test.cjs','test:ui':'node scripts/smoke.mjs','package:linux':'npm run build && node scripts/package-linux.mjs'};
await fs.writeFile(path.join(out,'package.json'),JSON.stringify(pkg,null,2)+'\n');
const lock=JSON.parse(await fs.readFile(path.join(out,'package-lock.json'),'utf8'));lock.packages[''].license='MIT';await fs.writeFile(path.join(out,'package-lock.json'),JSON.stringify(lock,null,2)+'\n');
await fs.copyFile(path.join(root,'linux/LICENSE'),path.join(out,'LICENSE'));
await fs.copyFile(path.join(root,'linux/README.md'),path.join(out,'README.md'));
await fs.writeFile(path.join(out,'.gitignore'),'node_modules/\ndist/\nrelease/\nqa/\n__pycache__/\n*.pyc\n.DS_Store\n');
console.log(out);
